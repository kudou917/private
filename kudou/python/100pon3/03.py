# 整数型の変数xとyにそれぞれ10と20を代入して、xとyを足した値を出力してください。
# 文字列型の変数nameとmessageにそれぞれ”John”と”Hello”を代入して、
# messageとnameを結合して”Hello John”と出力してください。

def main():
    x = 10
    y = 20
    name = "John"
    message = "Hello"
    print(x + y)
    print(message + name)
    return

if __name__ == "__main__":
    main()