# 整数型の変数xに10を代入して、”x is 10″という文字列をformatを使って出力してください。
# 文字列型の変数nameに”John”を代入して、”My name is John.”という文字列をformatを使って出力してください。

def main():
    x = 10
    print("x is",format(x))
    return

def sub():
    name = "John"
    print("My name is",format(name))
    return

if __name__ == "__main__":
    main()
    sub()

