# 整数型の変数xに10を代入して、xが10と等しい場合はTrue、そうでない場合はFalseを出力してください。
# 文字列型の変数nameに”John”を代入して、nameが”John”と等しい場合はTrue、
# そうでない場合はFalseを出力してください。

def main():
    x = 10
    if x == 10:
        print("True")
    else:
        print("False")
    return

def sub():
    name = "John"
    if name == "John": 
        print("True")
    else:
        print("False")
    return

if __name__ == "__main__":
    main()
    sub()