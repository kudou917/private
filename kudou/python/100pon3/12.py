# 文字列型の変数sに”Hello”を代入し、sを全て小文字に変換して出力してください。
# 文字列型の変数messageに”GOOD AFTERNOON”を代入し、
# messageを全て小文字に変換して出力してください。

def main():
    s = "Hello"
    print(s.lower())
    return

def sub():
    message = "GOOD AFTERNOON"
    print(message.lower())
    return

if __name__ == "__main__":
    main()
    sub()