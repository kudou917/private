# 問題 39 集合の和集合と共通部分
# 変数 x に {1, 2, 3} を代入し、変数 y に {3, 4, 5} を代入してください。
# 変数 x と変数 y の和集合 {1, 2, 3, 4, 5} を計算し、print 関数で出力してください。
# また、変数 x と変数 y の共通部分 {3} を計算し、print 関数で出力してください。

def main():
    x = {1, 2, 3}
    y = {3, 4, 5}
    print(x | y)
    print(x & y)

if __name__ == "__main__":
    main()